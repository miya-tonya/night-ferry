#!/usr/bin/env node
// Regenerate public/demo/demo-data.js (what the page's demo mode reads) from demo/data.json
// and the wallpaper list. Run it after editing either of them:  npm run demo-data
const fs = require("fs");
const path = require("path");
const ROOT = path.join(__dirname, "..");
const data = JSON.parse(fs.readFileSync(path.join(ROOT, "demo", "data.json"), "utf-8"));
const list = JSON.parse(fs.readFileSync(path.join(ROOT, "public", "assets", "backgrounds", "backgrounds.json"), "utf-8"));
const BG = "assets/backgrounds/";
data.backgrounds = list.map((b) => ({ name: b.name, url: BG + b.file, thumb: b.thumb ? BG + b.thumb : null, default: !!b.default }));
fs.writeFileSync(
  path.join(ROOT, "public", "demo", "demo-data.js"),
  "// Generated by tools/build-demo-data.js from demo/data.json — edit that file, not this one.\nwindow.NF_DEMO = " + JSON.stringify(data) + ";\n"
);
console.log("demo-data.js: " + data.entries.length + " articles, " + data.backgrounds.length + " wallpapers");
